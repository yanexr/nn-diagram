// Embeds Tailwind's theme.css so the browser compiler needs no network or fs access.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const root = dirname(require.resolve("tailwindcss/package.json"));
const theme = readFileSync(join(root, "theme.css"), "utf8");
const utilities = readFileSync(join(root, "utilities.css"), "utf8");
const out = `// Generated by scripts/gen-sources.mjs from tailwindcss@${require("tailwindcss/package.json").version}. Do not edit.
export const TAILWIND_THEME_CSS = ${JSON.stringify(theme)};
export const TAILWIND_UTILITIES_CSS = ${JSON.stringify(utilities)};
`;
writeFileSync(new URL("../src/tailwind/sources.generated.ts", import.meta.url), out);
console.log("wrote src/tailwind/sources.generated.ts");
